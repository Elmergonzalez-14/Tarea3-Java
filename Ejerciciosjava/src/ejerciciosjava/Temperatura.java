    private void btnCargarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarActionPerformed
        // TODO add your handling code here:
        indice = 0;
try {
    BufferedReader br = new BufferedReader(new FileReader(ruta));
    String linea = "";
    
    while ((linea = br.readLine()) != null && indice < temperaturas.length) {
        temperaturas[indice] = Double.parseDouble(linea);
        indice++;
    }
    br.close();
    JOptionPane.showMessageDialog(this, "Datos cargados correctamente en memoria.");
} catch (IOException | NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Error al cargar el archivo.");
}
        
    }//GEN-LAST:event_btnCargarActionPerformed

    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        // TODO add your handling code here:
        if (indice == 0) {
    JOptionPane.showMessageDialog(this, "Primero debe cargar los datos.");
    return;
}

double suma = 0;
int diasCalidos = 0;
int diasFrescos = 0;

for (int i = 0; i < indice; i++) {
    suma += temperaturas[i];
    if (temperaturas[i] >= 25.0) {
        diasCalidos++;
    } else {
        diasFrescos++;
    }
}

double promedio = suma / indice;

txtLista.setText("Análisis Climático\n");
txtLista.append("--------------------\n");
txtLista.append("Promedio de Temperatura: " + promedio + "\n");
txtLista.append("Días Cálidos (>= 25°): " + diasCalidos + "\n");
txtLista.append("Días Frescos (< 25°): " + diasFrescos + "\n");
        
    }//GEN-LAST:event_btnCalcularActionPerformed

