    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        String titulo = txtTitulo.getText();
String consola = txtConsola.getText();
int anio = Integer.parseInt(txtAnioLanzamiento.getText());

Videojuego juego = new Videojuego(titulo, consola, anio);
catalogo.add(juego);

String registro = "=== NUEVO VIDEOJUEGO ===\n"
                + "Título: " + juego.titulo + "\n"
                + "Consola: " + juego.consola + "\n"
                + "Año: " + juego.anioLanzamiento + "\n"
                + "-----------------------------\n\n";

try {
    File carpeta = new File("temp");
    if (!carpeta.exists()) {
        carpeta.mkdirs();
    }
    FileWriter fw = new FileWriter("temp/videojuegos.txt", true);
    PrintWriter pw = new PrintWriter(fw);
    pw.print(registro);
    pw.close();
} catch (Exception e) {
}

JOptionPane.showMessageDialog(this, "¡Juego agregado exitosamente!");
txtTitulo.setText("");
txtConsola.setText("");
txtAnioLanzamiento.setText("");
        
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnMostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarActionPerformed
        // TODO add your handling code here:
        txtResultados.setText("");

for (int i = 0; i < catalogo.size(); i++) {
    Videojuego j = catalogo.get(i);
    txtResultados.append("=== JUEGO #" + (i + 1) + " ===\n"
                       + "Título: " + j.titulo + "\n"
                       + "Consola: " + j.consola + "\n"
                       + "Año: " + j.anioLanzamiento + "\n"
                       + "-----------------------------\n\n");
}

txtResultados.append("Total de juegos registrados: " + catalogo.size() + "\n");
        
    }//GEN-LAST:event_btnMostrarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        if (catalogo.size() > 0) {
    catalogo.remove(catalogo.size() - 1);
    JOptionPane.showMessageDialog(this, "¡Último videojuego eliminado con éxito!");
} else {
    JOptionPane.showMessageDialog(this, "El catálogo está vacío.");
}
    }//GEN-LAST:event_btnEliminarActionPerformed

