    private void btnReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReporteActionPerformed
        // TODO add your handling code here:
        String ubicacion = "temp/sunombre_reporte_ventas.txt";

try {
    FileWriter escritor = new FileWriter(ubicacion);

    double totalVendido = 0;
    int ventasMayores500 = 0;

    for (int i = 0; i < indice; i++) {
        totalVendido += ventas[i];
        if (ventas[i] > 500) {
            ventasMayores500++;
        }
    }

    escritor.write("Reporte de Ventas\n");
    escritor.write("Total Vendido: " + totalVendido + "\n");
    escritor.write("Ventas superiores a Q500: " + ventasMayores500 + "\n");

    escritor.close();
    JOptionPane.showMessageDialog(this, "¡Archivo generado con éxito!");

} catch (IOException e) {
    JOptionPane.showMessageDialog(this, "Error al generar el archivo.");
}
    }//GEN-LAST:event_btnReporteActionPerformed

