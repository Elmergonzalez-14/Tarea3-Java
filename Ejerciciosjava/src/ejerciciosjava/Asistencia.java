    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        if (indice < asistentes.length) {
    asistentes[indice] = txtNombre.getText();
    txtLista.append(asistentes[indice] + "\n");
    indice++;
    txtNombre.setText("");
    JOptionPane.showMessageDialog(this, "Asistente registrado correctamente.");
} else {
    JOptionPane.showMessageDialog(this, "Ya se registraron los 5 asistentes.");
}
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnexportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnexportarActionPerformed
        // TODO add your handling code here:
        String ubicacion = "temp/sunombre_asistencia.txt";

try {
    FileWriter escritor = new FileWriter(ubicacion);

    escritor.write("Lista de Asistencia\n");
    for (int i = 0; i < indice; i++) {
        escritor.write((i + 1) + ". " + asistentes[i] + "\n");
    }

    escritor.close();
    JOptionPane.showMessageDialog(this, "¡Archivo generado con éxito!");

} catch (IOException e) {
    JOptionPane.showMessageDialog(this, "Error al generar el archivo.");
}
    }//GEN-LAST:event_btnexportarActionPerformed

    
