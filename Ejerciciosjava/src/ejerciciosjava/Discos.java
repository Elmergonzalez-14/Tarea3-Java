    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String albumBuscado = txtBuscar.getText().trim();
        int indiceEncontrado = -1;
        
       for (int i = 0; i < titulos.length; i++) {
            if (titulos[i] != null && titulos[i].equalsIgnoreCase(albumBuscado)) {
                indiceEncontrado = i;
                break;
            }
        }

        if (indiceEncontrado != -1) {
            lblAnioActual.setText(String.valueOf(anios[indiceEncontrado]));
            JOptionPane.showMessageDialog(this, "¡Álbum encontrado!");
        } else {
            lblAnioActual.setText("-");
            JOptionPane.showMessageDialog(this, "Álbum no encontrado.");
        }
        
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        String albumBuscado = txtBuscar.getText().trim();
        int indiceEncontrado = -1;
        
        for (int i = 0; i < titulos.length; i++) {
            if (titulos[i] != null && titulos[i].equalsIgnoreCase(albumBuscado)) {
                indiceEncontrado = i;
                break;
            }
        }

        if (indiceEncontrado != -1) {
            try {
                int nuevoAnio = Integer.parseInt(txtNuevoAnio.getText().trim());
                anios[indiceEncontrado] = nuevoAnio;

                // Sobrescribe el CSV de forma limpia
                FileWriter fw = new FileWriter(rutaDiscos, false);
                for (int i = 0; i < titulos.length; i++) {
                    if (titulos[i] != null) {
                        fw.write(titulos[i] + "," + anios[i] + "\n");
                    }
                }
                fw.close();

                lblAnioActual.setText(String.valueOf(nuevoAnio));
                JOptionPane.showMessageDialog(this, "¡Registro actualizado y guardado en archivo!");
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error al actualizar. Revisa el año ingresado.");
            }
        } else {
            JOptionPane.showMessageDialog(this, "Primero debes buscar un álbum válido.");
        }
        
        
    }//GEN-LAST:event_btnActualizarActionPerformed

