    private void cargarDatosAutomaticos() {
        try {
            File archivo = new File(rutaDiscos);
            if (archivo.exists()) {
                Scanner sc = new Scanner(archivo);
                int i = 0;
                while (sc.hasNextLine() && i < titulos.length) {
                    String linea = sc.nextLine();
                    String[] partes = linea.split(",");
                    titulos[i] = partes[0].trim();
                    anios[i] = Integer.parseInt(partes[1].trim());
                    i++;
                }
                sc.close();
            } else {
                JOptionPane.showMessageDialog(this, "No se encontró el archivo temp/Discos.csv");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar automáticamente los discos.");
        }
    }
   
